// Reads each component's real .tsx from packages/ui and emits it as a string map.
// This is what the "Code" tab, the Copy button and the Download button serve, so
// what visitors get is always byte-for-byte the source that ships in the package.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const uiRoot = join(here, "..", "..", "..", "packages", "ui");
const componentsDir = join(uiRoot, "src", "components");
const outFile = join(here, "..", "lib", "component-sources.ts");

const { version } = JSON.parse(readFileSync(join(uiRoot, "package.json"), "utf8"));

const toSlug = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])(\d)/g, "$1$2").toLowerCase();

const entries = readdirSync(componentsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => {
    const file = join(componentsDir, d.name, `${d.name}.tsx`);
    try {
      return { slug: toSlug(d.name), name: d.name, source: readFileSync(file, "utf8") };
    } catch {
      return null;
    }
  })
  .filter(Boolean)
  .sort((a, b) => a.slug.localeCompare(b.slug));

const body = entries
  .map((e) => `  ${JSON.stringify(e.slug)}: {
    name: ${JSON.stringify(e.name)},
    filename: ${JSON.stringify(`${e.name}.tsx`)},
    source: ${JSON.stringify(e.source)},
  },`)
  .join("\n");

mkdirSync(dirname(outFile), { recursive: true });

writeFileSync(
  outFile,
  `// GENERATED by scripts/generate-sources.mjs — do not edit by hand.
// Run \`pnpm build\` or \`pnpm dev\` in apps/docs to regenerate.

/** The version of piece-ui these sources were generated from. */
export const packageVersion = ${JSON.stringify(version)};

export type ComponentSource = {
  name: string;
  filename: string;
  source: string;
};

export const componentSources: Record<string, ComponentSource> = {
${body}
};

export function getSource(slug: string): ComponentSource | undefined {
  return componentSources[slug];
}
`,
  "utf8",
);

console.log(`✓ generated ${entries.length} component sources → lib/component-sources.ts`);
